import { readFileSync, writeFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { createHash } from "node:crypto";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const runtime = ["theme-surface.js", "fgpb-runtime.js", "cart-page-progress.js", "tiered-gift-sync.js", "bar-height.js", "unlock-celebrate.js"];
const assetPath = name => resolve(root, "extensions/free-gift-progress-bar/assets", name);
for (const name of runtime) {
  const source = readFileSync(resolve(root, "storefront-extension/src/runtime", name));
  if (check) {
    if (!source.equals(readFileSync(assetPath(name)))) throw new Error(`Stale runtime asset: ${name}`);
  } else writeFileSync(assetPath(name), source);
}
const coreBytes = statSync(assetPath("free-gift-progress-bar.js")).size;
const compatBytes = statSync(assetPath("cart-drawer-compat.js")).size;
const digest = createHash("sha256");
for (const name of ["free-gift-progress-bar.js", "cart-drawer-compat.js", ...runtime]) digest.update(name).update(readFileSync(assetPath(name)));
const manifest = {
  contentHash: digest.digest("hex"), coreAppBlockJs: "free-gift-progress-bar.js",
  coreAppBlockJsBytes: coreBytes, themeCheckAppBlockJsLimitBytes: 10000,
  coreExceedsThemeCheckLimit: coreBytes > 10000, optionalCompatJs: "cart-drawer-compat.js",
  optionalCompatJsBytes: compatBytes, coreIncludesThirdPartyAdapters: false,
  optionalAdapters: ["kwikcart", "upc-cart", "cart-popup"], optionalCompatDefaultEnabled: false,
  optionalCompatLabel: "Optional third-party cart compatibility (beta)",
};
const content = "// Generated by scripts/storefront-assets.mjs. Do not hand-edit.\nexport const STOREFRONT_ASSET_MANIFEST = " + JSON.stringify(manifest, null, 2) + " as const;\nexport type StorefrontAssetManifest = typeof STOREFRONT_ASSET_MANIFEST;\n";
const output = resolve(root, "app/lib/storefront-asset-manifest.ts");
if (check) {
  if (readFileSync(output, "utf8") !== content) throw new Error("Storefront metadata is stale. Run build:storefront.");
} else writeFileSync(output, content);
if (coreBytes > 10000) throw new Error(`Core asset exceeds 10000-byte budget: ${coreBytes}`);
console.log(`Storefront assets verified: core ${coreBytes} bytes; compatibility ${compatBytes} bytes.`);
